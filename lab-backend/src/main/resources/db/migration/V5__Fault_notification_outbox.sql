CREATE TABLE fault_notification_outbox (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  repair_order_id BIGINT NOT NULL,
  reservation_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  equipment_id BIGINT NOT NULL,
  start_time DATETIME NOT NULL,
  delivery_status TINYINT NOT NULL DEFAULT 0 COMMENT '0待投递 1站内可见 2失败待重试',
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at DATETIME DEFAULT NULL,
  confirmed_at DATETIME DEFAULT NULL,
  contacted_at DATETIME DEFAULT NULL,
  contacted_by BIGINT DEFAULT NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY uk_fault_event (repair_order_id,reservation_id),
  KEY idx_fault_delivery (delivery_status,next_attempt_at,id),
  KEY idx_fault_student (student_id,delivery_status,id),
  KEY idx_fault_contact (confirmed_at,contacted_at,start_time),
  CONSTRAINT fk_fault_repair FOREIGN KEY (repair_order_id) REFERENCES repair_order(id),
  CONSTRAINT fk_fault_reservation FOREIGN KEY (reservation_id) REFERENCES reservation(id),
  CONSTRAINT fk_fault_student FOREIGN KEY (student_id) REFERENCES `user`(id),
  CONSTRAINT fk_fault_equipment FOREIGN KEY (equipment_id) REFERENCES equipment(id),
  CONSTRAINT fk_fault_contacted_by FOREIGN KEY (contacted_by) REFERENCES `user`(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='设备故障取消预约的事务性站内通知事件';
